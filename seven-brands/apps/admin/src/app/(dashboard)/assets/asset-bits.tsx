import { renderAnimatedSvg, serialize, type AssetDefinition } from "@sb/asset";
import { Badge } from "@sb/ui";

const TONE = { draft: "neutral", in_review: "info", approved: "success", rejected: "danger", published: "success", archived: "neutral" } as const;
const LABEL = { draft: "Draft", in_review: "In review", approved: "Approved", rejected: "Rejected", published: "Published", archived: "Archived" } as const;

export function AssetStatusBadge({ status }: { status: keyof typeof TONE }) {
  return <Badge tone={TONE[status]}>{LABEL[status]}</Badge>;
}

export function ProvenanceBadge({ provenance }: { provenance: string }) {
  if (provenance === "fixture") return <Badge tone="warning">Fixture — not AI</Badge>;
  if (provenance === "ai-assisted") return <Badge tone="info">AI-assisted</Badge>;
  if (provenance === "rig") return <Badge>Rig</Badge>;
  return <Badge>{provenance}</Badge>;
}

/**
 * Animated (hover-to-play) preview. The markup is generated by our renderer from a
 * schema-validated definition — fixed element/attribute names, escaped values — never from raw input.
 */
export function AssetThumb({ ad, background }: { ad: AssetDefinition; background: string }) {
  const svg = serialize(renderAnimatedSvg(ad, { playOn: "hover", title: true }));
  return (
    <div
      className="flex aspect-square items-center justify-center rounded-[var(--radius)] p-4 [&>svg]:h-full [&>svg]:w-full"
      style={{ background }}
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}

export const BRAND_PREVIEW_BG: Record<string, string> = { sonicglyphs: "#0B0B14", cineglyphs: "#0A0A0A" };
export const previewBg = (brandSlug: string) => BRAND_PREVIEW_BG[brandSlug] ?? "#FFF8EC";
