import { renderAnimatedSvgString, renderFrameSvg, type AssetDefinition } from "@sb/asset";
import { exportLottie } from "./lottie";

/**
 * Text-only exporters (no esbuild, no native renderers), safe to import from a web server such as the storefront's
 * developer API. The full package builder in ./index adds raster, video and audio formats on top of these.
 */

export interface ExportOptions {
  tokens?: Record<string, string>;
  /** Pixel width for raster/video outputs (default 512; GIF 256). */
  size?: number;
  fps?: number;
  /** Background for formats without transparency (MP4). Default white. */
  background?: string;
  /** Number of loops rendered into GIF/MP4/WebM (default: enough for ~3 s, max 10). */
  loops?: number;
}

// ─── Vector ──────────────────────────────────────────────────────────────────

export function exportStaticSvg(ad: AssetDefinition, opts: ExportOptions = {}): string {
  return `<?xml version="1.0" encoding="UTF-8"?>\n${renderFrameSvg(ad, ad.a11y.reducedMotionFrame, { tokens: opts.tokens })}\n`;
}

export function exportAnimatedSvg(ad: AssetDefinition, opts: ExportOptions & { playOn?: "load" | "hover" } = {}): string {
  return renderAnimatedSvgString(ad, { tokens: opts.tokens, fps: opts.fps, playOn: opts.playOn });
}

/** JSON safe to embed inside a <script> element. */
export function scriptSafeJson(value: unknown): string {
  return JSON.stringify(value).replace(/</g, "\\u003c").replace(/>/g, "\\u003e").replace(/&/g, "\\u0026").replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029");
}

function pascal(slug: string) {
  return slug.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase()).replace(/^[0-9]/, (d) => `A${d}`);
}

export function exportReact(ad: AssetDefinition): { filename: string; source: string } {
  const name = pascal(ad.slug);
  const source = `// ${ad.name} — generated by DAOS. Requires daos-player.js (included) to be loaded once.
import { createElement, useEffect, useRef } from "react";
import "./daos-player.js";

const definition = ${JSON.stringify(ad, null, 2)} as const;

export interface ${name}Props {
  autoplay?: boolean;
  speed?: number;
  /** Color overrides, e.g. { primary: "#FF0066" }. Only the asset's own tokens are applied. */
  tokens?: Partial<Record<${Object.keys(ad.tokens).map((t) => JSON.stringify(t)).join(" | ") || "string"}, string>>;
  className?: string;
  /** Accessible label override. */
  label?: string;
  /** Scroll-driven playback: "scrub" follows the scroll position, "in-view" plays when half visible. */
  scroll?: "scrub" | "in-view";
  /** With scroll="scrub": how many times the animation repeats while the icon crosses the screen. */
  scrollLoops?: number;
}

export function ${name}({ autoplay = true, speed = 1, tokens, className, label, scroll, scrollLoops }: ${name}Props) {
  const ref = useRef<HTMLElement>(null);
  useEffect(() => {
    if (ref.current && tokens) ref.current.setAttribute("tokens", JSON.stringify(tokens));
  }, [tokens]);
  return createElement(
    "daos-asset",
    { ref, class: className, speed: String(speed), autoplay: autoplay ? "" : undefined, "aria-label": label, scroll, "scroll-loops": scrollLoops ? String(scrollLoops) : undefined },
    createElement("script", {
      type: "application/json",
      dangerouslySetInnerHTML: { __html: JSON.stringify(definition).replace(/</g, "\\\\u003c") },
    }),
  );
}

export default ${name};
`;
  return { filename: `${name}.tsx`, source };
}

export function escapeHtml(s: string) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

// ─── Developer API / CLI source files ────────────────────────────────────────

/** Formats the developer API can hand to the CLI and MCP server (text only; the CLI ships the player runtime). */
export const SOURCE_FORMATS = ["react", "web-component", "svg-animated", "svg", "lottie", "json"] as const;
export type SourceFormat = (typeof SOURCE_FORMATS)[number];

export interface SourceFile {
  /** Path relative to the icons folder. */
  path: string;
  content: string;
}

export interface IconSource {
  files: SourceFile[];
  /** Whether the files need daos-player.js next to them. */
  needsPlayer: boolean;
  /** How to use it, ready to paste. */
  usage: string;
}

/** The files for one icon in one format, as text, plus a ready-to-paste usage snippet. */
export function iconSourceFiles(ad: AssetDefinition, format: SourceFormat): IconSource {
  const slug = ad.slug;
  switch (format) {
    case "react": {
      const r = exportReact(ad);
      const name = r.filename.replace(/\.tsx$/, "");
      return { files: [{ path: r.filename, content: r.source }], needsPlayer: true, usage: `import { ${name} } from "./icons/${name}";\n\n<${name} />` };
    }
    case "web-component":
      return {
        files: [{ path: `${slug}.json`, content: JSON.stringify(ad, null, 2) }],
        needsPlayer: true,
        usage: `<script src="icons/daos-player.js" defer></script>\n<daos-asset src="icons/${slug}.json" autoplay></daos-asset>`,
      };
    case "svg-animated":
      return {
        files: [
          { path: `${slug}-animated.svg`, content: exportAnimatedSvg(ad) },
          { path: `${slug}-animated-hover.svg`, content: exportAnimatedSvg(ad, { playOn: "hover" }) },
        ],
        needsPlayer: false,
        usage: `<img src="icons/${slug}-animated.svg" alt="${escapeHtml(ad.a11y.label)}" width="64" height="64">  (no sound; use react or web-component for sound)`,
      };
    case "svg":
      return { files: [{ path: `${slug}.svg`, content: exportStaticSvg(ad) }], needsPlayer: false, usage: `<img src="icons/${slug}.svg" alt="${escapeHtml(ad.a11y.label)}" width="64" height="64">` };
    case "lottie":
      return { files: [{ path: `${slug}.lottie.json`, content: JSON.stringify(exportLottie(ad)) }], needsPlayer: false, usage: `Lottie JSON for lottie-web, lottie-ios, lottie-android, lottie-react-native or Flutter's lottie package (no sound).` };
    case "json":
      return { files: [{ path: `${slug}.json`, content: JSON.stringify(ad, null, 2) }], needsPlayer: false, usage: "Asset Definition JSON (for your own tooling)." };
  }
}
